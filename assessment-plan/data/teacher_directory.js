// Helper: Resolve canonical teacher name from numeric code or name
window.resolveTeacherFromCodeOrName = function(input) {
  if (!input) return '';
  const s = String(input).trim();
  if (!s) return '';
  if (window.TEACHER_CODE_MAP && window.TEACHER_CODE_MAP[s]) return window.TEACHER_CODE_MAP[s].name;
  const num = parseInt(s, 10);
  if (!isNaN(num) && window.TEACHER_CODE_MAP && window.TEACHER_CODE_MAP[String(num)]) return window.TEACHER_CODE_MAP[String(num)].name;
  const cleanKey = s.replace(/^(คุณครู|ครู)\s*/g, '').replace(/^(ว่าที่\s*ร\.ต\.หญิง|ว่าที่\s*ร\.ต\.|ว่าที่ร้อยตรีหญิง|ว่าที่ร้อยตรี|ดร\.|ผศ\.|รศ\.|ศ\.|นาย|นางสาว|น\.ส\.|นาง)\s*/g, '').replace(/\s+/g, '').trim();
  if (!cleanKey) return s;
  for (const info of Object.values(window.TEACHER_CODE_MAP || {})) {
    if (info.name === s) return info.name;
    const ik = info.name.replace(/^(คุณครู|ครู)\s*/g, '').replace(/^(ว่าที่\s*ร\.ต\.หญิง|ว่าที่\s*ร\.ต\.|ว่าที่ร้อยตรีหญิง|ว่าที่ร้อยตรี|ดร\.|ผศ\.|รศ\.|ศ\.|นาย|นางสาว|น\.ส\.|นาง)\s*/g, '').replace(/\s+/g, '').trim();
    if (ik === cleanKey) return info.name;
  }
  return s;
};
