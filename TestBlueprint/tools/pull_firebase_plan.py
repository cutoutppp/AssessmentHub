"""
Pull latest Term 2/2569 assessment-plan confirmations from Firestore (tradesimschool/survey_config)
into TestBlueprint/data/assessment_plan_sync.js so TestBlueprint runs 100% offline with zero sync delay.
"""
import json
import os
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_JS = os.path.join(ROOT, "data", "assessment_plan_sync.js")
LOCAL_COURSES_JSON = os.path.join(os.path.dirname(ROOT), "assessment-plan", "data", "courses_2_2569.json")
FIRESTORE_URL = (
    "https://firestore.googleapis.com/v1/projects/tradesimschool/"
    "databases/(default)/documents/survey_config?pageSize=300"
)


def decode_value(v):
    if not isinstance(v, dict):
        return None
    if "stringValue" in v:
        return v["stringValue"]
    if "integerValue" in v:
        return int(v["integerValue"])
    if "doubleValue" in v:
        return float(v["doubleValue"])
    if "booleanValue" in v:
        return bool(v["booleanValue"])
    if "nullValue" in v:
        return None
    if "arrayValue" in v:
        return [decode_value(item) for item in v["arrayValue"].get("values", [])]
    if "mapValue" in v:
        fields = v["mapValue"].get("fields", {})
        return {key: decode_value(item) for key, item in fields.items()}
    return None


def slim_units(units):
    res = []
    for u in units or []:
        if not isinstance(u, dict):
            continue
        item = {
            "unit_no": str(u.get("unit_no")) if u.get("unit_no") is not None else "",
            "unit_name": u.get("unit_name") or "",
            "hours": u.get("hours"),
            "score_k": u.get("score_k"),
            "score_p": u.get("score_p"),
            "score_a": u.get("score_a"),
            "score_total": u.get("score_total"),
            "indicators": u.get("indicators") or [],
        }
        if u.get("outcome_nos"):
            item["outcome_nos"] = u["outcome_nos"]
        res.append(item)
    return res


def main():
    with urllib.request.urlopen(FIRESTORE_URL, timeout=30) as resp:
        payload = json.loads(resp.read().decode("utf-8"))

    with open(LOCAL_COURSES_JSON, "r", encoding="utf-8") as f:
        local_courses = json.load(f)

    out = {}
    unit_diff_count = 0
    for doc in payload.get("documents", []):
        fields = {k: decode_value(v) for k, v in doc.get("fields", {}).items()}
        if fields.get("type") != "sgs_confirmation_2_2569":
            continue
        code = fields.get("course_code")
        if not code:
            continue

        entry = {
            "course_code": code,
            "teachers": fields.get("teachers") or [],
            "confirmed_by": fields.get("confirmed_by") or "",
            "confirmed_status": fields.get("confirmed_status") or "",
            "confirmed_at": fields.get("confirmed_at") or "",
            "classrooms": fields.get("classrooms") or "",
            "midterm_cutoff": fields.get("midterm_cutoff"),
            "mid_exam": fields.get("mid_exam"),
            "fin_exam": fields.get("fin_exam"),
            "mid_exam_duration": fields.get("mid_exam_duration"),
            "fin_exam_duration": fields.get("fin_exam_duration"),
            "pre_sum": fields.get("pre_sum"),
            "post_sum": fields.get("post_sum"),
            "grand_total": fields.get("grand_total"),
        }

        fb_units = slim_units(fields.get("units_snapshot"))
        lc_units = slim_units((local_courses.get(code) or {}).get("units"))
        if fb_units and fb_units != lc_units:
            unit_diff_count += 1
            entry["units_snapshot"] = fb_units

        out[code] = entry

    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    json_str = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    js_content = (
        "// Snapshot of Firebase Firestore tradesimschool/survey_config (type=sgs_confirmation_2_2569)\n"
        "// Generated by tools/pull_firebase_plan.py\n"
        f"window.ASSESSMENT_PLAN_SYNC = {json_str};\n"
    )
    with open(OUT_JS, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(
        f"Wrote {OUT_JS}: {len(out)} courses, {unit_diff_count} unit diffs, "
        f"{os.path.getsize(OUT_JS):,} bytes"
    )


if __name__ == "__main__":
    main()
